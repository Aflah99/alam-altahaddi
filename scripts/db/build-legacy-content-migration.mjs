// Builds supabase/migrations/20261118000400_legacy_content.sql from the bundled Task 05
// question bank and the Task 06 shop catalogue.
//
// The SQL is idempotent: running it again never duplicates rows and never re-publishes
// or overwrites questions an administrator has since edited, unpublished or archived.
//   * subjects/units/lessons: inserted if missing (by slug / number / legacy id)
//   * questions: inserted if their legacy id is new, then published in the same run
//   * shop items and academic review flags: inserted if missing
//
// Usage: node scripts/db/build-legacy-content-migration.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const DATA = 'src/questions/data/religion-values-g8'
const OUT = 'supabase/migrations/20261118000400_legacy_content.sql'
const PREFIX = 'rv8'
const UNIT_TITLES = ['الوحدة الأولى', 'الوحدة الثانية', 'الوحدة الثالثة', 'الوحدة الرابعة', 'الوحدة الخامسة']
const UMRAH_ID = 'rv8.u4.l4.21'

const q = (s) => (s === null || s === undefined ? 'null' : `'${String(s).replace(/'/g, "''")}'`)

const files = readdirSync(DATA)
  .filter((f) => f.endsWith('.json'))
  .map((f) => JSON.parse(readFileSync(join(DATA, f), 'utf8')))
  .sort((a, b) => a.unit - b.unit || a.lesson - b.lesson)

const units = [...new Set(files.map((f) => f.unit))]
const lessonRows = []
const questionRows = []
const optionRows = []
for (const f of files) {
  const legacyLesson = `u${f.unit}-l${f.lesson}`
  lessonRows.push(`(${f.unit}, ${q(legacyLesson)}, ${f.lesson}, ${q(f.title)}, ${f.pages[0]}, ${f.pages[1]})`)
  f.questions
    .filter((x) => (x.status ?? 'approved') === 'approved')
    .forEach((x, i) => {
      const id = `${PREFIX}.u${f.unit}.l${f.lesson}.${x.id}`
      const flagged = id === UMRAH_ID
      questionRows.push(
        `(${q(id)}, ${q(legacyLesson)}, ${q(x.q)}, ${q(x.hint)}, ${q(x.explain)}, ${x.difficulty ?? 2}, ${x.page}, ${i + 1}, ${flagged}, ${q(
          flagged ? 'حكم سفر المرأة للعمرة دون محرم منشور كما ورد في الكتيّب؛ يحتاج إلى تأكيد معلّم للصياغة (Task 05 review item).' : '',
        )})`,
      )
      x.options.forEach((t, k) => optionRows.push(`(${q(id)}, '${'abcd'[k]}', ${q(t)}, ${k === 0})`))
    })
}

const catalog = readFileSync('src/economy/catalog.ts', 'utf8')
const shopRows = [...catalog.matchAll(/\{ id: '([^']+)', category: '([^']+)',(?: characterId: '([^']+)',)? name: '([^']+)', description: '([^']+)', price: (\d+) \}/g)].map(
  (m, i) => `(${q(m[1])}, ${q(m[2])}, ${q(m[4])}, ${q(m[5])}, ${m[6]}, ${q(m[3] ?? null)}, ${i + 1})`,
)
if (shopRows.length !== 15) throw new Error(`expected 15 shop items, parsed ${shopRows.length}`)

const sql = `-- GENERATED by scripts/db/build-legacy-content-migration.mjs — do not edit by hand.
-- Imports the Task 05 «ديني قيمي» bank (${files.length} lessons, ${questionRows.length} questions), the Task 06 shop
-- catalogue (${shopRows.length} items) and the open academic review items. Idempotent (see the script).

do $$
declare
  v_subject uuid;
begin
  insert into public.subjects (slug, name_ar, name_en, grade, semester, description, icon, theme, sort_order, status, source_label)
  values ('religion-values', 'ديني قيمي', 'Religion and Values', 8, 1,
          'دروس ومهمات أسئلة من كتيّب مراجعة ديني قيمي للصف الثامن. ادخل العالم وابحث عن البوابة.',
          'star', 'meadow', 1, 'published', 'كتيّب ديني قيمي')
  on conflict (slug) do nothing;
  select id into v_subject from public.subjects where slug = 'religion-values';

  insert into public.units (subject_id, number, title, sort_order, status)
  select v_subject, n, (array[${UNIT_TITLES.map(q).join(', ')}])[n], n, 'published'
  from unnest(array[${units.join(', ')}]) n
  on conflict (subject_id, number) do nothing;

  insert into public.lessons (subject_id, unit_id, legacy_id, number, title, page_start, page_end, sort_order, status)
  select v_subject, u.id, l.legacy_id, l.number, l.title, l.page_start, l.page_end, l.number, 'published'
  from (values
    ${lessonRows.join(',\n    ')}
  ) as l (unit_number, legacy_id, number, title, page_start, page_end)
  join public.units u on u.subject_id = v_subject and u.number = l.unit_number
  on conflict (legacy_id) do nothing;
end $$;

drop table if exists _legacy_q, _legacy_o, _legacy_new;
create temporary table _legacy_q (legacy_id text, lesson text, text text, hint text, explanation text, difficulty int, page int, sort_key int, flagged boolean, note text);
create temporary table _legacy_o (legacy_id text, option_id char(1), text text, is_correct boolean);
create temporary table _legacy_new (id uuid);

insert into _legacy_q values
${questionRows.join(',\n')};

insert into _legacy_o values
${optionRows.join(',\n')};

with ins as (
  insert into public.questions (legacy_id, subject_id, lesson_id, text, hint, explanation, difficulty, status, origin,
                                source_label, source_page, sort_key, needs_academic_review, academic_note)
  select q.legacy_id, l.subject_id, l.id, q.text, q.hint, q.explanation, q.difficulty, 'draft', 'legacy_import',
         'كتيّب ديني قيمي', q.page, q.sort_key, q.flagged, q.note
  from _legacy_q q join public.lessons l on l.legacy_id = q.lesson
  on conflict (legacy_id) do nothing
  returning id
)
insert into _legacy_new select id from ins;

insert into public.question_options (question_id, option_id, text, is_correct)
select qq.id, o.option_id, o.text, o.is_correct
from _legacy_o o join public.questions qq on qq.legacy_id = o.legacy_id
where qq.id in (select id from _legacy_new)
on conflict do nothing;

update public.questions set status = 'published' where id in (select id from _legacy_new);

insert into public.content_reviews (question_id, action, to_status, note)
select id, 'publish', 'published', 'Imported from the Task 05 bank (manually verified against the booklet).' from _legacy_new;

select public.refresh_lesson_missions(l.id) from public.lessons l
where l.id in (select lesson_id from public.questions where id in (select id from _legacy_new));

insert into public.shop_items (id, category, name_ar, description, price, character_id, sort_order) values
${shopRows.join(',\n')}
on conflict (id) do nothing;

insert into public.academic_flags (key, subject_id, lesson_id, question_id, source_page, title, details, handling, origin)
select f.key, s.id, l.id, qq.id, f.page, f.title, f.details, f.handling, 'legacy_task05'
from (values
  ('legacy-p26', 'u1-l6', null, 26, 'الصفحة ٢٦ — غزوة الأحزاب: صف «النتائج» في الجدول',
   'يبدو صف «النتائج» معكوسًا (المسلمون «خسروا سمعتهم وهيبتهم» والأحزاب «نالوا العزة والرفعة») ويناقض السؤال ٢٤ في الكتيّب نفسه.',
   'غير منشور؛ يحتاج إلى مراجعة معلّم.'),
  ('legacy-p82', 'u3-l5', null, 82, 'الصفحة ٨٢ — الحكم الشرعي التكليفي: السؤال ١٢ج',
   'يحدد الكتيّب إجابتين صحيحتين (الفرض والمندوب) لعبارة «كل ما يُثاب فاعله»؛ ليس سؤالًا بإجابة واحدة.',
   'غير منشور؛ يحتاج إلى مراجعة معلّم.'),
  ('legacy-p119-q16d', 'u4-l6', null, 119, 'الصفحة ١١٩ — احترام الخصوصية: السؤال ١٦، الموقف «د»',
   'الإجابة المطبوعة للموقف «د» منسوخة من الموقف «ج» ولا تطابق الموقف.',
   'غير منشور؛ يحتاج إلى مراجعة معلّم.'),
  ('legacy-umrah-q21', 'u4-l4', ${q(UMRAH_ID)}, 109, 'الصفحة ١٠٩ — العمرة: السؤال ٢١ (سفر المرأة دون محرم)',
   'منشور كما ورد في الكتيّب؛ يحتاج إلى تأكيد معلّم للصياغة وعرضه بوصفه موقف الكتيّب.',
   'منشور دون تعديل، ومعلَّم بأنه يحتاج إلى مراجعة أكاديمية.')
) as f (key, lesson, question, page, title, details, handling)
join public.subjects s on s.slug = 'religion-values'
left join public.lessons l on l.legacy_id = f.lesson
left join public.questions qq on qq.legacy_id = f.question
on conflict (key) do nothing;

drop table if exists _legacy_q, _legacy_o, _legacy_new;
`
writeFileSync(OUT, sql)
console.log(`wrote ${OUT}: ${files.length} lessons, ${questionRows.length} questions, ${optionRows.length} options, ${shopRows.length} shop items`)
